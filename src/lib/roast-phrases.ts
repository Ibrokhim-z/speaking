export function getPerQuestionPhrase(score: number): string {
    const category = score >= 7 ? 'good' : score >= 4 ? 'mid' : 'bad';
    const phrases = perQuestionPhrasesRu[category];
    return phrases[Math.floor(Math.random() * phrases.length)];
}
