export function getRandomRoast(score: number): string {
    const bracket = roastPhrases.find(r => score >= r.minScore && score <= r.maxScore);
    if (!bracket) return 'Интересный результат! Давай разберёмся подробнее.';
    const phrases = bracket.phrases;
    return phrases[Math.floor(Math.random() * phrases.length)];
}

